def tarot_chunks():
    if len(TEXTS)!=len(CARDS): raise ValueError('Catalogue/text count mismatch')
    rows=[]
    for card,line in zip(CARDS,TEXTS):
        upright,reversed_text,traits,keyword=line.split('|')
        for orientation,text in [('upright',upright),('reversed',reversed_text)]:
            rows.append(_chunk(card,orientation,'general',text,traits,keyword))
            if card.card_id in FOCUS:
                for topic,application in zip(TOPICS[1:],APPLICATIONS[card.card_id][orientation]):
                    rows.append(_chunk(card,orientation,topic,application,traits,keyword))
    return rows

def fixture_chunks():
    return [row for row in tarot_chunks() if row['card_id'] in FOCUS]

def validate_chunks(rows):
    if len({r['id'] for r in rows})!=len(rows): raise ValueError('Duplicate chunk IDs')
    if len({r['content_hash'] for r in rows})!=len(rows): raise ValueError('Duplicate content hashes')
    if len({r['text'] for r in rows})!=len(rows): raise ValueError('Duplicate text')
    pairs={}
    for row in rows:
        pairs.setdefault((row['card_id'],row['topic']),{})[row['orientation']]=row['text']
    for directions in pairs.values():
        if len(directions)!=2: raise ValueError('Missing orientation')
        grams=lambda t:{t[i:i+4] for i in range(len(t)-3)}
        a,b=map(grams,directions.values())
        if len(a&b)/max(1,len(a|b))>.70: raise ValueError('Copied opposite orientation text')
