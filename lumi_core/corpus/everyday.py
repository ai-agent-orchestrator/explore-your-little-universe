def everyday_cards():
    from lumi_core.catalog.traits import SUGGESTIONS
    suggestions = {key: (trait, text) for key, trait, text in SUGGESTIONS}
    rows = []
    for group, (category, content) in enumerate(THEMES.items(), 1):
        lines = content.strip().splitlines()
        if len(lines) != 10:
            raise ValueError(f'{category}: expected ten situations')
        for index, line in enumerate(lines, 1):
            title, problem, keys = line.split('|')
            keys = keys.split(',')
            rows.append({
                'id': f'daily-{group:02}-{index:02}', 'title': title,
                'text': problem + ' 작은 시도: ' + ' '.join(suggestions[key][1] for key in keys),
                'category': category, 'traits': sorted({suggestions[key][0] for key in keys}),
                'tips': keys, 'kind': 'scenario', 'subject_kind': '', 'subject': '',
                'document_id': f'daily-theme-{group:02}', 'document_title': f'{category} 일상 사례',
                'source': '마음의 지도 편집 · 직접 작성한 가상 일상 사례 v2',
                'source_url': '', 'reviewed_on': '2026-11-22',
                'editorial_note': '외부 글을 옮긴 내용이 아닌 직접 작성한 상황과 행동 예시.',
            })
    return rows
